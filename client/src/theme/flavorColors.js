// A neutral fallback for flavors added later without a color
export const DEFAULT_FLAVOR_COLOR = "#cfd8dc";

export function flavorColor(flavor) {
  const key = String(flavor || "").trim().toLowerCase().replace(/\s+/g, "-");
  return FLAVOR_COLORS[key] || DEFAULT_FLAVOR_COLOR;
}
